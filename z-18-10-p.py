# Задача: напишите программу, которая запрашивает у пользователя числа до тех пор,
# пока не будет введено число 0. После завершения ввода, программа должна вывести
# сумму всех введённых (положительных?) чисел.
#
# Что нам потребуется: while, переменная, print, input try-except, int(),

x = 0
while True:
    try:
        num = int(input("Введите число: "))
        if num == 0:
            break

        x += num

    except ValueError:
        print("Ошибка")
print(x)